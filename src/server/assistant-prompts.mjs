export function buildSummary(session) {
  const records = session.messages.filter((message) => message.role === "user");
  const assessment = session.assessment;
  const lines = [
    "接诊摘要草稿｜待咨询师核实",
    "",
    `个案代号：${session.name}`,
    `年龄范围（录入）：${session.ageRange || "未了解"}`,
    `初始主诉（录入原文）：${session.concern || "未记录"}`,
    "",
    "来访记录摘录（仅复述已录入内容）：",
    ...(records.length
      ? records.map((message, index) => `${index + 1}. ${message.content}`)
      : ["尚无访谈记录。"]),
    "",
    "量表筛查：",
    assessment
      ? `${assessment.instrument.toUpperCase()}：${assessment.score} 分；${assessment.severity}。${assessment.interpretation}`
      : "尚未完成量表筛查。",
    "",
    "咨询师笔记（录入原文）：",
    session.notes || "未记录。",
    "",
    "安全线索提醒：",
    session.risk === "urgent"
      ? "记录中出现需要立即核实的安全线索。请查阅原文并完成现场风险评估；系统不会自动消除此提醒。"
      : session.risk === "attention"
        ? "存在需进一步核实的安全线索或筛查提示，请由咨询师完成直接询问。"
        : "本地规则未触发提醒；这不代表已完成风险评估或不存在风险。",
    "",
    "待了解：具体起始时间与频率、功能影响、相关身心病史、既往求助及用药情况、支持资源和当前安全状况。已在记录中讨论的项目请由咨询师核对后更新。",
    "",
    "本摘要在本地按录入内容整理，未调用外部模型；不构成诊断、病历签署或治疗方案。",
  ];
  return lines.join("\n");
}
