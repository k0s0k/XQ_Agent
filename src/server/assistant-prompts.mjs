export function localIntakeResponse(session, content) {
  const areas = [
    [
      /睡|失眠|夜醒|早醒/,
      "睡眠情况",
      "最近睡眠变化从什么时候开始？每周大约出现几晚，对白天状态有什么影响？",
    ],
    [
      /焦虑|担心|紧张|害怕|心慌/,
      "担忧与紧张",
      "这些担忧通常在什么情境出现？当时身体、想法和行为分别发生了什么变化？",
    ],
    [
      /低落|难过|抑郁|开心|兴趣|疲惫/,
      "情绪与日常功能",
      "这种感受持续了多久？它对工作、学习、人际关系或自我照顾有什么具体影响？",
    ],
    [
      /关系|家人|父母|伴侣|朋友|同事/,
      "关系与支持",
      "在这段经历中，哪些互动最让您困扰？目前有没有让您感到被理解或支持的人？",
    ],
  ];
  const match = areas.find(([pattern]) => pattern.test(content));
  const focus = match
    ? `本条记录涉及“${match[1]}”，可优先了解发生情境与影响。`
    : "可以先围绕本次求助原因、持续时间与日常功能进行开放式访谈。";
  const firstQuestion =
    match?.[2] ?? "这次最希望获得帮助的困扰是什么？最近一次让您明显感到困扰的情境是怎样的？";
  const disclaimer = !session.consent
    ? "尚未取得外部模型处理同意；本次仅生成本地访谈提示。"
    : "当前为本地演示模式，以下是规则生成的访谈提示。";
  return `${disclaimer}\n\n${focus}\n\n建议咨询师选择性追问：\n1. ${firstQuestion}\n2. 您已经尝试过哪些应对方式？哪些稍有帮助、哪些没有帮助？\n3. 您希望本次咨询带来怎样的具体变化？\n\n已知信息以记录原文为准；症状频率、病史和安全状况仍需面谈核实，不能据此作出诊断。`;
}

